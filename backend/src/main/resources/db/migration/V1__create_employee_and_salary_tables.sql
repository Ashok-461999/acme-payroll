CREATE TABLE employee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(255) NOT NULL,
    department VARCHAR(40) NOT NULL,
    job_title VARCHAR(100) NOT NULL,
    country VARCHAR(2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    hire_date DATE NOT NULL,
    current_salary NUMERIC(15, 2) NOT NULL,
    current_salary_effective_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_employee_code UNIQUE (employee_code),
    CONSTRAINT uk_employee_email UNIQUE (email),
    CONSTRAINT chk_employee_salary_positive CHECK (current_salary > 0),
    CONSTRAINT chk_employee_country_length CHECK (char_length(country) = 2),
    CONSTRAINT chk_employee_currency_length CHECK (char_length(currency) = 3)
);

CREATE TABLE salary_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    effective_date DATE NOT NULL,
    reason VARCHAR(30) NOT NULL,
    note VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_salary_employee FOREIGN KEY (employee_id) REFERENCES employee (id),
    CONSTRAINT uk_salary_employee_effective_date UNIQUE (employee_id, effective_date),
    CONSTRAINT chk_salary_amount_positive CHECK (amount > 0)
);

CREATE INDEX idx_employee_department ON employee (department);
CREATE INDEX idx_employee_country ON employee (country);
CREATE INDEX idx_employee_currency ON employee (currency);
CREATE INDEX idx_employee_hire_date ON employee (hire_date);
CREATE INDEX idx_salary_employee_date ON salary_record (employee_id, effective_date);
